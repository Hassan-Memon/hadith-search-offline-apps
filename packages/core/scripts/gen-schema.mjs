// Embeds schema.sql into a TypeScript module so bundlers (Metro, Vite) and
// Node all get the schema without a raw-file import. schema.sql stays the
// single source of truth; this file is regenerated on every build.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sql = readFileSync(resolve(root, 'schema.sql'), 'utf8').replace(/\r\n/g, '\n');
const version = Number(/PRAGMA user_version\s*=\s*(\d+)/.exec(sql)?.[1] ?? 0);
if (!version) throw new Error('schema.sql must set PRAGMA user_version');

const out = `// GENERATED by scripts/gen-schema.mjs from schema.sql — do not edit.
export const SCHEMA_VERSION = ${version};
export const SCHEMA_SQL = ${JSON.stringify(sql)};
`;
mkdirSync(resolve(root, 'src/db'), { recursive: true });
writeFileSync(resolve(root, 'src/db/schema.generated.ts'), out);
console.log(`schema.generated.ts written (user_version ${version})`);
